#!/usr/bin/env python3
"""Generate inference/src/tokenizer/case_table.zig from a pinned Unicode Character Database.

The table is the case side of the letter categories the o200k splitter
(o200k.zig) needs beside pre.zig's letter, mark, number and space classes:
code points of General_Category Lu or Lt (cased capitals, in its upper class
only) and of Ll (in its lower class only), as inclusive ranges. Every other
letter (Lm, Lo) is in both classes. The table is committed; this script only
regenerates it. UnicodeData.txt is cached under .reference/ucd/<version>/ and
checked against the digest tokenizer-nfc.py pins.

    python3 scripts/fixtures/tokenizer-case.py
"""

import argparse
import hashlib
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd"
ROOT = Path(__file__).resolve().parents[2]
DIGEST = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
UPPER, LOWER = 1, 2
CLASSES = {"Lu": UPPER, "Lt": UPPER, "Ll": LOWER}

parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument(
    "--ucd-dir", type=Path, default=ROOT / ".reference/ucd" / VERSION, help="where the UCD files are cached/downloaded"
)
parser.add_argument("--output", type=Path, default=ROOT / "inference/src/tokenizer/case_table.zig")
parser.add_argument("--offline", action="store_true", help="fail instead of downloading")
args = parser.parse_args()


def unicode_data():
    path = args.ucd_dir / "UnicodeData.txt"
    if not path.exists():
        if args.offline:
            parser.error(f"missing {path}; run without --offline")
        args.ucd_dir.mkdir(parents=True, exist_ok=True)
        url = f"{BASE}/UnicodeData.txt"
        print("fetch", url)
        with urllib.request.urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != DIGEST:
        parser.error(f"{path}: sha256 {digest} differs from the pinned {DIGEST}")
    return data.decode()


def main():
    ranges = []
    first = None
    for line in unicode_data().splitlines():
        f = line.split(";")
        cp, name, category = int(f[0], 16), f[1], f[2]
        if name.endswith(", First>"):
            first = cp
            continue
        span = range(first, cp + 1) if first is not None and name.endswith(", Last>") else range(cp, cp + 1)
        first = None
        value = CLASSES.get(category)
        if value is None:
            continue
        for c in span:
            if ranges and ranges[-1][1] == c - 1 and ranges[-1][2] == value:
                ranges[-1][1] = c
            else:
                ranges.append([c, c, value])
    items = [f".{{ 0x{a:X}, 0x{b:X}, {v} }}," for a, b, v in ranges]
    width = max(len(x) for x in items)
    body = ["    " + " ".join(x.ljust(width) for x in items[i : i + 4]).rstrip() for i in range(0, len(items), 4)]
    out = "\n".join(
        [
            f"//! Generated by scripts/fixtures/tokenizer-case.py from UCD {VERSION}; do not edit.",
            "//! Cased letters for o200k.zig; Unicode data is Copyright © Unicode, Inc.,",
            "//! under the Unicode License (THIRD_PARTY_NOTICES.md).",
            "",
            f'pub const version = "{VERSION}";',
            "pub const upper = 1;",
            "pub const lower = 2;",
            "",
            "/// Lu and Lt (`upper`) and Ll (`lower`) code points: first, last (inclusive), class.",
            "pub const ranges = [_][3]u21{",
            *body,
            "};",
            "",
        ]
    )
    args.output.write_text(out)
    print(f"wrote {args.output}: {len(ranges)} ranges")


if __name__ == "__main__":
    main()
